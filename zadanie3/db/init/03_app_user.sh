#!/bin/bash
set -e

: "${APP_DB_PASSWORD:?APP_DB_PASSWORD is required}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE theatre_app WITH LOGIN PASSWORD '${APP_DB_PASSWORD}'
        NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;

    REVOKE CREATE ON SCHEMA public FROM PUBLIC;

    GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO theatre_app;
    GRANT USAGE  ON SCHEMA public TO theatre_app;

    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES    IN SCHEMA public TO theatre_app;
    GRANT USAGE, SELECT                  ON ALL SEQUENCES IN SCHEMA public TO theatre_app;

    ALTER DEFAULT PRIVILEGES IN SCHEMA public
        GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO theatre_app;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public
        GRANT USAGE, SELECT ON SEQUENCES TO theatre_app;
EOSQL
