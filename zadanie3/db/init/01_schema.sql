CREATE TABLE plays (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    duration_minutes INTEGER      NOT NULL,
    age_limit        INTEGER      NOT NULL,
    archived         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_play_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_play_age_limit CHECK (age_limit >= 0 AND age_limit <= 18)
);

CREATE TABLE theatre_halls (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255) NOT NULL,
    capacity INTEGER      NOT NULL,
    CONSTRAINT uq_hall_name UNIQUE (name),
    CONSTRAINT chk_hall_capacity CHECK (capacity > 0)
);

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT chk_user_email CHECK (email LIKE '%@%')
);

CREATE TABLE performances (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    play_id    BIGINT         NOT NULL,
    hall_id    BIGINT         NOT NULL,
    start_time TIMESTAMP      NOT NULL,
    base_price NUMERIC(12, 2) NOT NULL,
    status     VARCHAR(20)    NOT NULL,
    CONSTRAINT fk_performance_play FOREIGN KEY (play_id) REFERENCES plays (id),
    CONSTRAINT fk_performance_hall FOREIGN KEY (hall_id) REFERENCES theatre_halls (id),
    CONSTRAINT chk_performance_price CHECK (base_price >= 0),
    CONSTRAINT chk_performance_status CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED'))
);

CREATE INDEX idx_performance_play ON performances (play_id);
CREATE INDEX idx_performance_hall ON performances (hall_id);
CREATE INDEX idx_performance_start_time ON performances (start_time);

CREATE TABLE tickets (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT      NOT NULL,
    user_id        BIGINT,
    seat_number    INTEGER     NOT NULL,
    status         VARCHAR(20) NOT NULL,
    CONSTRAINT fk_ticket_performance FOREIGN KEY (performance_id)
        REFERENCES performances (id) ON DELETE CASCADE,
    CONSTRAINT fk_ticket_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_ticket_seat CHECK (seat_number > 0),
    CONSTRAINT chk_ticket_status CHECK (status IN ('RESERVED', 'SOLD', 'REFUNDED', 'CANCELLED'))
);

CREATE INDEX idx_ticket_performance ON tickets (performance_id);
CREATE INDEX idx_ticket_user ON tickets (user_id);

CREATE UNIQUE INDEX uq_ticket_active_seat ON tickets (performance_id, seat_number)
    WHERE status IN ('RESERVED', 'SOLD');
